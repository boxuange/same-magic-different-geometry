"""S39 end-to-end exact Fraction/SymPy membership check for the finite frozen-H
physical model. This proof is NOT about unrestricted CPTP or finite epsilon.
"""
from __future__ import annotations
import json,hashlib
from pathlib import Path
from fractions import Fraction as F
import numpy as np
import sympy as sp
ROOT=Path(__file__).resolve().parent

def main():
    mg=json.loads((ROOT/'certified_three_magic_frozen_physical_s38_results.json').read_text())
    ci=json.loads((ROOT/'certified_five_ci_frozen_physical_s39_results.json').read_text())
    bw=json.loads((ROOT/'certified_witness_frozen_physical_s38_results.json').read_text())
    archive=ROOT/'data/historical_20261009_grams.npz'
    gram=np.load(archive)
    report=json.loads((ROOT/'resource_manifold_audit.json').read_text())['20261009']
    names=report['diagnostic_keys']; assert len(names)==8
    hR=F(13,10**8);hB=F(1,200000)
    full={k:F(v['frozen_physical_to_archive_bound_exact_fraction']) for k,v in mg['matrix_results'].items()}
    full.update({k:F(v['frozen_binary64_input_to_archive_CI_gram_error_bound_fraction']) for k,v in ci['results'].items()})
    assert set(names)==set(full),(names,full.keys())
    assert all(v<hR for v in full.values())
    w=F(bw['total_frozen_physical_witness_to_archive_fraction']);assert w<hB
    RAT=lambda x:sp.Rational(*float(x).as_integer_ratio())
    G=[sp.Matrix(13,13,lambda i,j:RAT(gram[k][i,j])) for k in names]
    B=sp.Matrix(13,13,lambda i,j:RAT(gram['witness'][i,j]))
    X=sp.Matrix([RAT(v) for v in report['numerical_continuation_not_exact_roots'][1]['coefficients']])
    e0=sp.Matrix([1]+[0]*12)
    piv=[0,1,4,6,7,9,10,11,12]
    D=sp.Matrix([[2*(g*X)[j] for j in piv] for g in G]+[[1]*9])
    assert D.det(method='domain-ge')!=0
    A=D.inv()
    Ainf=max(sum(abs(A[i,j]) for j in range(9)) for i in range(9))
    F0=sp.Matrix([(X.T*g*X)[0]-g[0,0] for g in G]+[sum(X)-1])
    eta=max(abs(v) for v in A*F0)
    s=sum(abs(v) for v in X)
    d=sum(abs(v) for v in X-e0)
    L=2*max(sum(abs(g[j,k]) for j in piv for k in piv) for g in G)
    radius=sp.Rational(37,2000000)
    etaR=eta+Ainf*sp.Rational(hR.numerator,hR.denominator)*(s*s+1)
    q=Ainf*(2*9*sp.Rational(hR.numerator,hR.denominator)*s+(L+2*9**2*sp.Rational(hR.numerator,hR.denominator))*radius)
    assert q<1 and etaR+q*radius<radius
    wc=(X.T*B*X)[0];w0=B[0,0]
    wvar=radius*(2*sum(abs(t) for t in B*X)+radius*sum(abs(B[i,j]) for i in piv for j in piv))
    wbias=sp.Rational(hB.numerator,hB.denominator)*(d+9*radius)*(s+9*radius+1)
    lower=wc-w0-wvar-wbias
    assert lower>sp.Rational(1,100000)
    outcome={'theorem_status':'PASS: STRICT EXISTENCE THEOREM IN A FROZEN-INPUT FINITE PHYSICAL CODE',
      'exactly_equal_quantities_at_leading_order':names,
      'code':'Six [[5,1,3]] tensors on the two-triangle bridge graph; 13 Clifford orbit coefficient directions, fixed decoder-dependent magic quotient and first-order source-independent region-unitary CI',
      'input_scope':'Six binary64 weighted Hermitian matrices generated by seed 20261009 interpreted as exact rational input coefficients; no numerical rounding in mathematical code definition',
      'resource_error_threshold_fraction':str(hR),'witness_error_threshold_fraction':str(hB),
      'certified_resource_error_upper_fractions':{k:str(v) for k,v in full.items()},
      'certified_resource_error_upper_decimals':{k:float(v) for k,v in full.items()},
      'certified_witness_error_upper_fraction':str(w),
      'banach_pivots_zero_based':piv,'banach_radius_fraction':str(radius),
      'banach_contraction_factor_upper_fraction':str(q),
      'banach_self_mapping_upper_fraction':str((etaR+q*radius)/radius),
      'geometric_Z_witness_difference_strict_lower_fraction':str(lower),
      'geometric_Z_witness_difference_strict_lower_decimal':float(lower),
      'certified_witness_difference_exceeds_1e_minus_5':True,
      'archive_sha256':hashlib.sha256(archive.read_bytes()).hexdigest(),
      'does_not_prove':['exact equality at finite epsilon','global optimal CPTP coherent information','full unrestricted non-local magic over other subsystem partitions','a continuous dynamical spacetime metric','Einstein equation','a theorem independent of this tensor graph and chosen source/recovery definitions','bit-by-bit correctness of unverified NumPy/BLAS computations']}
    (ROOT/'full_frozen_physical_theorem_s39.json').write_text(json.dumps(outcome,indent=2,ensure_ascii=False)+'\n')
    print('PASS physical frozen coefficient eight-diagnostic equality theorem')
    print('max resource error=',max(float(v) for v in full.values()),'witness upper=',float(w))
    print('witness difference lower=',float(lower))
    return outcome

if __name__=='__main__':main()
